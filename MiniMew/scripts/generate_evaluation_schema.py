"""从离线Pydantic类型真源生成schema；不导入在线应用。"""

import argparse
import json
from pathlib import Path

from minimew.evaluation.gate import EvaluationArtifact, GatePolicy
from minimew.evaluation.protocol import Corpus, Dataset, ObservationSet
from minimew.evaluation.scoring import Report

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    models = {
        "corpus": Corpus,
        "dataset": Dataset,
        "observation": ObservationSet,
        "report": Report,
        "gate-policy": GatePolicy,
        "artifact": EvaluationArtifact,
    }
    stale = []
    for name, model in models.items():
        schema = model.model_json_schema()
        schema["$comment"] = "Generated by scripts/generate_evaluation_schema.py; do not edit."
        content = json.dumps(schema, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
        path = ROOT / "evals/rag/schema" / f"{name}.json"
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
    if stale:
        parser.exit(1, "Schema drift: " + ", ".join(stale) + "\n")
    print("Evaluation schema: OK")


if __name__ == "__main__":
    main()
